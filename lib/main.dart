import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';

import 'common.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'screens/admin/admin_home.dart';
import 'screens/auth_screen.dart';
import 'screens/citizen/citizen_home.dart';
import 'screens/driver/driver_home.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const App());
}

class App extends StatelessWidget {
  const App({super.key});
  @override
  Widget build(BuildContext context) => MaterialApp(
        title: 'Smart Waste',
        debugShowCheckedModeBanner: false,
        theme: ThemeData(colorSchemeSeed: Colors.green, useMaterial3: true),
        home: const AuthGate(),
      );
}

/// Routes the user to the right home screen based on role in users/{uid}.
class AuthGate extends StatelessWidget {
  const AuthGate({super.key});
  @override
  Widget build(BuildContext context) {
    return StreamBuilder<User?>(
      stream: FirebaseAuth.instance.authStateChanges(),
      builder: (c, s) {
        if (s.connectionState == ConnectionState.waiting) return loader();
        final u = s.data;
        if (u == null) return const AuthScreen();
        return StreamBuilder<DocumentSnapshot<Map<String, dynamic>>>(
          stream: db.doc('users/${u.uid}').snapshots(),
          builder: (c, d) {
            if (!d.hasData || !d.data!.exists) return loader();
            switch (d.data!.data()!['role']) {
              case 'admin':
                return const AdminHome();
              case 'driver':
                return const DriverHome();
              default:
                return const CitizenHome();
            }
          },
        );
      },
    );
  }
}
